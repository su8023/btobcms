<?php

namespace Modules\MailNotifier\Console\Commands;

use App\Models\Inquiry;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Mail;
use Modules\MailNotifier\Mail\InquiryConfirmation;
use Throwable;

class MailTestCommand extends Command
{
    protected $signature = 'mail:test {--email=}';

    protected $description = '发送 InquiryConfirmation 测试邮件，验证 MailNotifier 邮件链路（MAIL_MAILER=log 时写入日志）';

    public function handle(): int
    {
        if (! config('mail-notifier.enabled')) {
            $this->warn('提示：MAIL_NOTIFIER_ENABLED=false，插件当前处于禁用状态（测试邮件仍会发送）。');
        }

        $to = $this->option('email') ?: config('mail-notifier.admin_emails.0');

        if (blank($to)) {
            $this->error('未指定收件邮箱，且 .env 未配置 INQUIRY_ADMIN_EMAILS。');
            $this->line('用法：php artisan mail:test --email=you@example.com，或在 .env 中设置 INQUIRY_ADMIN_EMAILS=a@example.com,b@example.com');

            return self::FAILURE;
        }

        // 构造一条不落库的示例询盘用于渲染模板
        $inquiry = new Inquiry([
            'name' => 'Test Buyer',
            'email' => $to,
            'phone' => '+86 138 0000 0000',
            'company' => 'Test Company Ltd.',
            'country' => 'United States',
            'message' => "This is a test inquiry generated by the mail:test command.\nIt is used to verify that MailNotifier templates and the mail pipeline work correctly.",
            'source' => 'mail:test',
            'landing_url' => config('app.url'),
        ]);

        try {
            Mail::to($to)->send(new InquiryConfirmation($inquiry));
        } catch (Throwable $e) {
            $this->error('发送失败：'.$e->getMessage());

            return self::FAILURE;
        }

        if (config('mail.default') === 'log') {
            $this->info("测试邮件已写入日志 storage/logs/laravel.log（MAIL_MAILER=log，收件人：{$to}）。");
        } else {
            $this->info('测试邮件已发送至 '.$to.'（当前 MAIL_MAILER='.config('mail.default').'）。');
        }

        return self::SUCCESS;
    }
}
